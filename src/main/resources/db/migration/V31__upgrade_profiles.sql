DECLARE
    missing TEXT;
BEGIN
    SELECT string_agg(DISTINCT sp.upgrade_name, ', ') INTO missing
    FROM staging_profile sp
    LEFT JOIN upgrade u ON u.name = sp.upgrade_name AND u.upgrade_type = sp.upgrade_type
    WHERE u.id IS NULL;
    IF missing IS NOT NULL THEN
        RAISE EXCEPTION 'Profiles for unknown upgrades: %', missing;
    END IF;
END $$;

