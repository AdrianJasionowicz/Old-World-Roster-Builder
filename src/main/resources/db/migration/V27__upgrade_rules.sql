CREATE TABLE upgrade_group
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(255) NOT NULL UNIQUE,
    max_choices       INTEGER,
    lord_points_limit DOUBLE PRECISION,
    hero_points_limit DOUBLE PRECISION
);

ALTER TABLE upgrade
    ADD COLUMN upgrade_group_id BIGINT REFERENCES upgrade_group (id),
    ADD COLUMN unique_in_army   BOOLEAN NOT NULL DEFAULT FALSE;

ALTER TABLE unit
    ADD COLUMN magic_items_points_limit  DOUBLE PRECISION,
    ADD COLUMN magic_banner_points_limit DOUBLE PRECISION;

DELETE
FROM unit_upgrade uu
    USING unit u, upgrade up
WHERE uu.unit_id = u.id
  AND uu.upgrade_id = up.id
  AND u.unit_type NOT IN ('LORDS', 'HERO')
  AND up.upgrade_type IN ('MAGIC_WEAPON', 'MAGIC_ARMOUR', 'MAGIC_ITEM')
  AND NOT EXISTS (SELECT 1 FROM selected_upgrade s WHERE s.unit_upgrade_id = uu.id);

CREATE TEMPORARY TABLE mistyped_upgrade (name, target_type) AS
VALUES ('Hand Weapon', 'FREE_UPGRADE'),
       ('Level 1 Wizard', 'UNIT_EQUIPMENT'),
       ('Level 2 Wizard', 'UNIT_EQUIPMENT'),
       ('Poisoned Attacks', 'UNIT_EQUIPMENT');

UPDATE unit_upgrade uu
SET upgrade_id = target.id
FROM upgrade source,
     upgrade target,
     mistyped_upgrade m
WHERE uu.upgrade_id = source.id
  AND source.name = m.name
  AND source.upgrade_type = 'MAGIC_ITEM'
  AND target.name = m.name
  AND target.upgrade_type = m.target_type
  AND NOT EXISTS (SELECT 1 FROM unit_upgrade other WHERE other.unit_id = uu.unit_id AND other.upgrade_id = target.id);

DELETE
FROM upgrade up
    USING mistyped_upgrade m
WHERE up.name = m.name
  AND up.upgrade_type = 'MAGIC_ITEM'
  AND NOT EXISTS (SELECT 1 FROM unit_upgrade uu WHERE uu.upgrade_id = up.id);

DROP TABLE mistyped_upgrade;

