UPDATE unit u
SET magic_banner_points_limit = CASE WHEN u.unit_type = 'CORE' THEN 25 ELSE 50 END
WHERE u.unit_type NOT IN ('LORDS', 'HERO')
  AND EXISTS (SELECT 1
              FROM unit_upgrade uu
                       JOIN upgrade up ON up.id = uu.upgrade_id
              WHERE uu.unit_id = u.id
                AND up.upgrade_type = 'MAGIC_BANNER');

