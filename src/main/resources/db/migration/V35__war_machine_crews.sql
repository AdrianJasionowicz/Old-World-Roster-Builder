DO $$
DECLARE
    missing TEXT;
BEGIN
    SELECT string_agg(s.faction || ' ' || s.unit_name, ', ') INTO missing
    FROM staging_unit_profile s
    WHERE NOT EXISTS (SELECT 1 FROM unit u WHERE u.unit_faction = s.faction AND u.name = s.unit_name);
    IF missing IS NOT NULL THEN
        RAISE EXCEPTION 'Unknown units for crew profiles: %', missing;
    END IF;
END $$;

