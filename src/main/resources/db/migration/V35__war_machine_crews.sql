CREATE TABLE unit_profile (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id     BIGINT       NOT NULL REFERENCES unit (id) ON DELETE CASCADE,
    position    INTEGER      NOT NULL,
    name        VARCHAR(255) NOT NULL,
    m           VARCHAR(10),
    ws          VARCHAR(10),
    bs          VARCHAR(10),
    s           VARCHAR(10),
    t           VARCHAR(10),
    w           VARCHAR(10),
    i           VARCHAR(10),
    a           VARCHAR(10),
    ld          VARCHAR(10),
    basic_save  VARCHAR(10),
    ward_save   VARCHAR(10),
    UNIQUE (unit_id, position)
);

CREATE INDEX idx_unit_profile_unit ON unit_profile (unit_id);

