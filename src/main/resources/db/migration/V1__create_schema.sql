-- Schema of the roster builder. Hibernate only validates it (ddl-auto=validate), it never changes it.
-- Enum columns hold the Java enum names (@Enumerated(EnumType.STRING)).

CREATE TABLE login_user
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   VARCHAR(255) NOT NULL UNIQUE,
    password   VARCHAR(255) NOT NULL,
    email      VARCHAR(255) NOT NULL UNIQUE,
    role       VARCHAR(255) NOT NULL,
    is_enabled BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE army
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255)     NOT NULL,
    description  VARCHAR(255),
    points_limit DOUBLE PRECISION NOT NULL,
    faction      VARCHAR(255)     NOT NULL,
    owner_id     BIGINT           NOT NULL REFERENCES login_user (id) ON DELETE CASCADE
);

CREATE INDEX idx_army_owner ON army (owner_id);

-- =========================
-- Unit catalog
-- =========================

CREATE TABLE unit_stats
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    m          INTEGER,
    ws         INTEGER,
    bs         INTEGER,
    s          INTEGER,
    t          INTEGER,
    w          INTEGER,
    i          INTEGER,
    a          INTEGER,
    ld         INTEGER,
    -- 0 means "no save"
    basic_save INTEGER,
    ward_save  INTEGER
);

CREATE TABLE unit
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 VARCHAR(255)     NOT NULL,
    points_cost_per_unit DOUBLE PRECISION NOT NULL,
    min_quantity         INTEGER          NOT NULL,
    unit_type            VARCHAR(255)     NOT NULL,
    unit_faction         VARCHAR(255)     NOT NULL,
    unit_stats_id        BIGINT UNIQUE REFERENCES unit_stats (id)
);

CREATE INDEX idx_unit_faction ON unit (unit_faction);

CREATE TABLE special_rule
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    description VARCHAR(255)
);

CREATE TABLE unit_special_rule
(
    unit_id         BIGINT NOT NULL REFERENCES unit (id) ON DELETE CASCADE,
    special_rule_id BIGINT NOT NULL REFERENCES special_rule (id),
    PRIMARY KEY (unit_id, special_rule_id)
);

-- =========================
-- Upgrades: catalog, effects and per-unit prices
-- =========================

CREATE TABLE upgrade
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255) NOT NULL,
    upgrade_type VARCHAR(255) NOT NULL,
    description  VARCHAR(1000),
    UNIQUE (name, upgrade_type)
);

-- Stat effect of an upgrade, e.g. Halberd: S ADD 1. See ModifierOperation for the operations.
CREATE TABLE upgrade_stat_modifier
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    upgrade_id     BIGINT       NOT NULL REFERENCES upgrade (id) ON DELETE CASCADE,
    stat           VARCHAR(255) NOT NULL,
    operation      VARCHAR(255) NOT NULL,
    modifier_value INTEGER      NOT NULL
);

CREATE INDEX idx_upgrade_stat_modifier_upgrade ON upgrade_stat_modifier (upgrade_id);

-- Which unit can take which upgrade and for how many points.
CREATE TABLE unit_upgrade
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id     BIGINT           NOT NULL REFERENCES unit (id) ON DELETE CASCADE,
    upgrade_id  BIGINT           NOT NULL REFERENCES upgrade (id),
    points_cost DOUBLE PRECISION NOT NULL,
    UNIQUE (unit_id, upgrade_id)
);

-- =========================
-- Rosters
-- =========================

CREATE TABLE army_unit
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quantity   INTEGER          NOT NULL,
    total_cost DOUBLE PRECISION NOT NULL,
    army_id    BIGINT           NOT NULL REFERENCES army (id) ON DELETE CASCADE,
    -- no cascade: a unit used in a roster cannot be removed from the catalog (API answers 409)
    unit_id    BIGINT           NOT NULL REFERENCES unit (id)
);

CREATE INDEX idx_army_unit_army ON army_unit (army_id);

CREATE TABLE selected_upgrade
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quantity        INTEGER NOT NULL,
    army_unit_id    BIGINT  NOT NULL REFERENCES army_unit (id) ON DELETE CASCADE,
    unit_upgrade_id BIGINT  NOT NULL REFERENCES unit_upgrade (id)
);

CREATE INDEX idx_selected_upgrade_army_unit ON selected_upgrade (army_unit_id);
